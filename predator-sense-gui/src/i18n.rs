//! Simple internationalization module.
//! Language is explicit (saved user preference in Settings), defaulting to
//! English on first run - no OS locale auto-detection.

use std::sync::OnceLock;

static LANG: OnceLock<Lang> = OnceLock::new();

#[derive(Clone, Copy, PartialEq)]
pub enum Lang {
    Pt,
    En,
    Es,
    Zh,
    Ja,
    Ru,
    De,
}

pub fn lang() -> Lang {
    *LANG.get_or_init(|| Lang::En)
}

/// Seed the language from a saved user preference ("pt"/"en"/"es"/"zh"/"ja"/
/// "ru"/"de"). Must be called before the first `t()`/`lang()` call (i.e.
/// before any UI is built) to have an effect - defaults to English for
/// `None`, an unrecognized value, or an already-set OnceLock (first-run / no
/// config.json entry yet).
pub fn init(saved_override: Option<&str>) {
    let lang = match saved_override {
        Some("pt") => Lang::Pt,
        Some("es") => Lang::Es,
        Some("zh") => Lang::Zh,
        Some("ja") => Lang::Ja,
        Some("ru") => Lang::Ru,
        Some("de") => Lang::De,
        _ => Lang::En,
    };
    let _ = LANG.set(lang);
}

pub fn is_pt() -> bool {
    lang() == Lang::Pt
}

/// Get translated string by key
pub fn t(key: &str) -> &str {
    match lang() {
        Lang::Pt => t_pt(key),
        Lang::En => t_en(key),
        Lang::Es => t_es(key),
        Lang::Zh => t_zh(key),
        Lang::Ja => t_ja(key),
        Lang::Ru => t_ru(key),
        Lang::De => t_de(key),
    }
}

